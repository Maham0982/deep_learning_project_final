const menuToggle = document.getElementById('menuToggle');
const navLinks = document.getElementById('navLinks');
menuToggle.addEventListener('click', () => navLinks.classList.toggle('open'));
navLinks.querySelectorAll('a').forEach(link => link.addEventListener('click', () => navLinks.classList.remove('open')));

const imageInput = document.getElementById('imageInput');
const chooseImage = document.getElementById('chooseImage');
const previewImage = document.getElementById('previewImage');
const uploadPlaceholder = document.getElementById('uploadPlaceholder');
const demoTitle = document.getElementById('demoTitle');
const demoText = document.getElementById('demoText');

chooseImage.addEventListener('click', () => imageInput.click());
imageInput.addEventListener('change', () => {
  const file = imageInput.files && imageInput.files[0];
  if (!file) return;
  if (!file.type.startsWith('image/')) {
    demoTitle.textContent = 'Please select an image';
    demoText.textContent = 'The selected file is not a recognized image format.';
    return;
  }
  const reader = new FileReader();
  reader.onload = event => {
    previewImage.src = event.target.result;
    previewImage.hidden = false;
    uploadPlaceholder.hidden = true;
    demoTitle.textContent = 'Image preview ready';
    demoText.textContent = `${file.name} is displayed locally. No image is uploaded and no model prediction is being generated by this static demo.`;
  };
  reader.readAsDataURL(file);
});
document.getElementById('resetDemo').addEventListener('click', () => {
  imageInput.value = '';
  previewImage.removeAttribute('src');
  previewImage.hidden = true;
  uploadPlaceholder.hidden = false;
  demoTitle.textContent = 'Ready for your image';
  demoText.textContent = 'Select a file to preview it here. Real predictions require a working model inference backend.';
});

document.querySelectorAll('[data-placeholder]').forEach(link => {
  link.addEventListener('click', event => {
    event.preventDefault();
    const label = link.querySelector('.resource-link');
    const oldText = label.textContent;
    label.textContent = 'Add your URL in index.html';
    setTimeout(() => label.textContent = oldText, 2600);
  });
});
